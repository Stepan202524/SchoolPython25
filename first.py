# Loop's: (циклы)
# while
# for
counter = 0  # обнуляем счётчик
# цикл из 5ти итераций
while counter < 5:
    print(f'Iteration number {counter}')
    # counter = counter + 1  # инкремент
    counter += 1 # краткая запись бинарным оператором
while counter > 0:
    print(f'Деитерация {counter}')
    counter -= 1  #декремент
